CREATE TABLE controlled_operation_run (
    run_id text PRIMARY KEY,
    idempotency_key text NOT NULL UNIQUE,
    command_hash text NOT NULL CHECK (
        command_hash ~ '^sha256:[0-9a-f]{64}$'
    ),
    command_json text NOT NULL CHECK (command_json IS JSON OBJECT),
    decision_date date NOT NULL,
    status text NOT NULL CHECK (
        status IN (
            'CREATED',
            'WAITING_FOR_STATIC_INPUTS',
            'STATIC_READY',
            'WAITING_FOR_DECISION_WINDOW',
            'DECISION_WINDOW_RUNNING',
            'DATA_BLOCKED',
            'DEADLINE_MISSED',
            'OUTCOME_PENDING',
            'SETTLED',
            'FAILED'
        )
    ),
    current_stage text CHECK (
        current_stage IS NULL OR current_stage IN (
            'CALENDAR_UNIVERSE_FREEZE',
            'DAILY_SOURCE_FREEZE',
            'DAILY_DATASET',
            'STATIC_FEATURES',
            'OPERATIONAL_RESEARCH',
            'CANDIDATE_SET',
            'CANDIDATE_MINUTE_ACQUISITION',
            'INTRADAY_DATASET',
            'INTRADAY_FEATURE_OVERLAY',
            'SIGNAL',
            'PATH_FORECAST',
            'ENTRY_ASSESSMENT',
            'OPERATION_PACKAGE',
            'OUTCOME_SETTLEMENT'
        )
    ),
    version bigint NOT NULL CHECK (version >= 1),
    created_at timestamptz NOT NULL,
    updated_at timestamptz NOT NULL,
    settled_at timestamptz,
    CHECK ((status = 'SETTLED') = (settled_at IS NOT NULL))
);

CREATE TABLE controlled_operation_stage (
    run_id text NOT NULL,
    stage_name text NOT NULL CHECK (
        stage_name IN (
            'CALENDAR_UNIVERSE_FREEZE',
            'DAILY_SOURCE_FREEZE',
            'DAILY_DATASET',
            'STATIC_FEATURES',
            'OPERATIONAL_RESEARCH',
            'CANDIDATE_SET',
            'CANDIDATE_MINUTE_ACQUISITION',
            'INTRADAY_DATASET',
            'INTRADAY_FEATURE_OVERLAY',
            'SIGNAL',
            'PATH_FORECAST',
            'ENTRY_ASSESSMENT',
            'OPERATION_PACKAGE',
            'OUTCOME_SETTLEMENT'
        )
    ),
    status text NOT NULL CHECK (
        status IN ('PENDING', 'IN_PROGRESS', 'FAILED', 'COMPLETED')
    ),
    version bigint NOT NULL CHECK (version >= 1),
    claim_id text,
    claim_epoch bigint NOT NULL DEFAULT 0 CHECK (claim_epoch >= 0),
    lease_acquired_at timestamptz,
    lease_expires_at timestamptz,
    heartbeat_at timestamptz,
    receipt_id text UNIQUE,
    receipt_hash text CHECK (
        receipt_hash IS NULL OR receipt_hash ~ '^sha256:[0-9a-f]{64}$'
    ),
    last_error text,
    PRIMARY KEY (run_id, stage_name),
    FOREIGN KEY (run_id)
        REFERENCES controlled_operation_run(run_id) ON DELETE RESTRICT,
    CHECK ((receipt_id IS NULL) = (receipt_hash IS NULL)),
    CHECK (
        (
            status = 'IN_PROGRESS'
            AND claim_id IS NOT NULL
            AND claim_epoch >= 1
            AND lease_acquired_at IS NOT NULL
            AND lease_expires_at IS NOT NULL
            AND heartbeat_at IS NOT NULL
            AND receipt_id IS NULL
        ) OR (
            status != 'IN_PROGRESS'
            AND claim_id IS NULL
            AND lease_acquired_at IS NULL
            AND lease_expires_at IS NULL
            AND heartbeat_at IS NULL
        )
    ),
    CHECK (
        (status = 'COMPLETED' AND receipt_id IS NOT NULL)
        OR (status != 'COMPLETED' AND receipt_id IS NULL)
    )
);

CREATE TABLE controlled_operation_attempt (
    attempt_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    run_id text NOT NULL,
    stage_name text NOT NULL,
    attempt_number bigint NOT NULL CHECK (attempt_number >= 1),
    claim_id text NOT NULL,
    claim_epoch bigint NOT NULL CHECK (claim_epoch >= 1),
    stage_version bigint NOT NULL CHECK (stage_version >= 2),
    started_at timestamptz NOT NULL,
    lease_expires_at timestamptz NOT NULL,
    heartbeat_at timestamptz NOT NULL,
    completed_at timestamptz,
    status text NOT NULL CHECK (
        status IN ('STARTED', 'COMPLETED', 'FAILED', 'LEASE_EXPIRED')
    ),
    error_message text,
    UNIQUE (run_id, stage_name, attempt_number),
    UNIQUE (run_id, stage_name, claim_epoch),
    FOREIGN KEY (run_id, stage_name)
        REFERENCES controlled_operation_stage(run_id, stage_name)
        ON DELETE RESTRICT,
    CHECK (
        (status = 'STARTED' AND completed_at IS NULL)
        OR (status != 'STARTED' AND completed_at IS NOT NULL)
    )
);

CREATE TABLE controlled_operation_receipt (
    receipt_id text PRIMARY KEY,
    receipt_hash text NOT NULL CHECK (
        receipt_hash ~ '^sha256:[0-9a-f]{64}$'
    ),
    run_id text NOT NULL,
    stage_name text NOT NULL,
    attempt_number bigint NOT NULL CHECK (attempt_number >= 1),
    receipt_json text NOT NULL CHECK (receipt_json IS JSON OBJECT),
    created_at timestamptz NOT NULL,
    UNIQUE (run_id, stage_name),
    UNIQUE (run_id, stage_name, receipt_hash),
    UNIQUE (receipt_id, run_id, stage_name),
    FOREIGN KEY (run_id, stage_name, attempt_number)
        REFERENCES controlled_operation_attempt(run_id, stage_name, attempt_number)
        ON DELETE RESTRICT
);

CREATE INDEX controlled_operation_receipt_attempt_idx
ON controlled_operation_receipt(run_id, stage_name, attempt_number);

CREATE TABLE controlled_operation_child_run (
    run_id text NOT NULL,
    stage_name text NOT NULL,
    reference_kind text NOT NULL CHECK (
        reference_kind IN (
            'DAILY_ACQUISITION_RUN',
            'STATIC_FEATURE_RUN',
            'MINUTE_ACQUISITION_BATCH',
            'INTRADAY_FEATURE_RUN',
            'CANONICAL_LIFECYCLE_RUN',
            'OUTCOME_RUN'
        )
    ),
    child_run_id text NOT NULL,
    child_receipt_hash text NOT NULL CHECK (
        child_receipt_hash ~ '^sha256:[0-9a-f]{64}$'
    ),
    receipt_id text NOT NULL,
    PRIMARY KEY (run_id, reference_kind, child_run_id),
    FOREIGN KEY (receipt_id, run_id, stage_name)
        REFERENCES controlled_operation_receipt(receipt_id, run_id, stage_name)
        ON DELETE RESTRICT
);

CREATE INDEX controlled_operation_child_receipt_idx
ON controlled_operation_child_run(receipt_id, run_id, stage_name);

CREATE TABLE controlled_operation_event (
    event_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    run_id text NOT NULL,
    stage_name text,
    event_type text NOT NULL CHECK (
        event_type IN (
            'RUN_CREATED',
            'RUN_RESUMED',
            'RUN_STATUS_CHANGED',
            'STAGE_CLAIMED',
            'STAGE_HEARTBEAT',
            'STAGE_COMPLETED',
            'STAGE_FAILED',
            'LEASE_EXPIRED',
            'RECEIPT_RECORDED'
        )
    ),
    event_time timestamptz NOT NULL,
    payload_json text NOT NULL CHECK (payload_json IS JSON OBJECT),
    FOREIGN KEY (run_id)
        REFERENCES controlled_operation_run(run_id) ON DELETE RESTRICT,
    FOREIGN KEY (run_id, stage_name)
        REFERENCES controlled_operation_stage(run_id, stage_name)
        ON DELETE RESTRICT
);

CREATE INDEX controlled_operation_run_status_date_idx
