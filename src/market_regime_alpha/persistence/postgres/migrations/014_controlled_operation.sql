CREATE FUNCTION guard_controlled_stage_mutation()
RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    IF TG_OP = 'DELETE' THEN
        RAISE EXCEPTION 'Controlled operation stages cannot be deleted';
    END IF;
    IF OLD.status = 'COMPLETED' THEN
        RAISE EXCEPTION 'Completed Controlled operation stage is immutable';
    END IF;
    IF OLD.status = 'IN_PROGRESS' AND NEW.status = 'IN_PROGRESS' AND (
        NEW.claim_id IS DISTINCT FROM OLD.claim_id
        OR NEW.claim_epoch IS DISTINCT FROM OLD.claim_epoch
    ) THEN
        RAISE EXCEPTION 'Active Controlled operation claim cannot be overwritten';
    END IF;
    RETURN NEW;
END;
$$;

CREATE TRIGGER controlled_operation_stages_no_delete
BEFORE DELETE ON controlled_operation_stage
FOR EACH ROW EXECUTE FUNCTION guard_controlled_stage_mutation();
CREATE TRIGGER controlled_operation_completed_stage_immutable
BEFORE UPDATE ON controlled_operation_stage
FOR EACH ROW EXECUTE FUNCTION guard_controlled_stage_mutation();

CREATE FUNCTION guard_controlled_run_mutation()
RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    IF TG_OP = 'DELETE' THEN
        RAISE EXCEPTION 'Controlled operation runs cannot be deleted';
    END IF;
    IF NEW.run_id IS DISTINCT FROM OLD.run_id
       OR NEW.idempotency_key IS DISTINCT FROM OLD.idempotency_key
       OR NEW.command_hash IS DISTINCT FROM OLD.command_hash
       OR NEW.command_json IS DISTINCT FROM OLD.command_json
       OR NEW.decision_date IS DISTINCT FROM OLD.decision_date
       OR NEW.created_at IS DISTINCT FROM OLD.created_at THEN
        RAISE EXCEPTION 'Controlled operation command identity is immutable';
    END IF;
    IF (OLD.status = 'OUTCOME_PENDING'
        AND NEW.status NOT IN ('OUTCOME_PENDING', 'SETTLED'))
       OR (OLD.status = 'SETTLED' AND NEW.status != 'SETTLED') THEN
        RAISE EXCEPTION 'Controlled operation terminal status cannot regress';
    END IF;
    RETURN NEW;
END;
$$;

CREATE TRIGGER controlled_operation_runs_no_delete
