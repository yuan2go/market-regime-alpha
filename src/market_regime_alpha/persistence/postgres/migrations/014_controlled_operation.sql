CREATE FUNCTION guard_controlled_attempt_mutation()
RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    IF TG_OP = 'DELETE' THEN
        RAISE EXCEPTION 'Controlled operation attempts are append-only';
    END IF;
    IF OLD.status != 'STARTED' THEN
        RAISE EXCEPTION 'Settled Controlled operation attempts are immutable';
    END IF;
    IF NEW.run_id IS DISTINCT FROM OLD.run_id
       OR NEW.stage_name IS DISTINCT FROM OLD.stage_name
       OR NEW.attempt_number IS DISTINCT FROM OLD.attempt_number
       OR NEW.claim_id IS DISTINCT FROM OLD.claim_id
       OR NEW.claim_epoch IS DISTINCT FROM OLD.claim_epoch
       OR NEW.stage_version IS DISTINCT FROM OLD.stage_version
       OR NEW.started_at IS DISTINCT FROM OLD.started_at THEN
        RAISE EXCEPTION 'Controlled operation attempt identity is immutable';
    END IF;
    RETURN NEW;
END;
$$;

