CREATE TABLE continuous_runtime_tick (
    run_id text NOT NULL,
    tick_id text NOT NULL,
    idempotency_key text NOT NULL UNIQUE,
    tick_hash text NOT NULL CHECK (
        tick_hash ~ '^sha256:[0-9a-f]{64}$'
    ),
    tick_json text NOT NULL CHECK (tick_json IS JSON OBJECT),
    tick_sequence bigint NOT NULL CHECK (tick_sequence >= 1),
    observed_at timestamptz NOT NULL,
    session_phase text NOT NULL CHECK (
        session_phase IN (
            'PRE_MARKET',
            'MORNING_SESSION',
            'MIDDAY_RECESS',
            'AFTERNOON_SESSION',
            'DECISION_WINDOW',
            'MARKET_CLOSED'
        )
    ),
    status text NOT NULL CHECK (
        status IN (
            'PENDING',
            'IN_PROGRESS',
            'COMPLETED',
            'FAILED',
            'DATA_BLOCKED'
        )
    ),
    version bigint NOT NULL CHECK (version >= 1),
    claim_id text,
    fencing_token bigint NOT NULL DEFAULT 0 CHECK (fencing_token >= 0),
    lease_acquired_at timestamptz,
    lease_expires_at timestamptz,
    heartbeat_at timestamptz,
    provider_attempt_id bigint,
    evidence_commit_id text,
    change_decision_id text,
    receipt_id text UNIQUE,
    receipt_hash text CHECK (
        receipt_hash IS NULL OR receipt_hash ~ '^sha256:[0-9a-f]{64}$'
    ),
    receipt_json text CHECK (
        receipt_json IS NULL OR receipt_json IS JSON OBJECT
    ),
    last_error text,
    retry_at timestamptz,
    created_at timestamptz NOT NULL,
    updated_at timestamptz NOT NULL,
    completed_at timestamptz,
    PRIMARY KEY (run_id, tick_id),
    UNIQUE (run_id, tick_sequence),
    FOREIGN KEY (run_id)
        REFERENCES continuous_research_run(run_id) ON DELETE RESTRICT,
    CHECK ((receipt_id IS NULL) = (receipt_hash IS NULL)),
    CHECK ((receipt_id IS NULL) = (receipt_json IS NULL)),
    CHECK (
        (
            status = 'IN_PROGRESS'
            AND claim_id IS NOT NULL
            AND fencing_token >= 1
            AND lease_acquired_at IS NOT NULL
            AND lease_expires_at IS NOT NULL
            AND heartbeat_at IS NOT NULL
            AND completed_at IS NULL
        ) OR (
            status != 'IN_PROGRESS'
            AND claim_id IS NULL
            AND lease_acquired_at IS NULL
            AND lease_expires_at IS NULL
            AND heartbeat_at IS NULL
        )
    ),
    CHECK (
        (
            status = 'COMPLETED'
            AND receipt_id IS NOT NULL
            AND completed_at IS NOT NULL
        ) OR (
            status != 'COMPLETED'
            AND receipt_id IS NULL
        )
    )
);

