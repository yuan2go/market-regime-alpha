CREATE FUNCTION guard_continuous_research_run_mutation()
RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    IF TG_OP = 'DELETE' THEN
        RAISE EXCEPTION 'Continuous Research runs cannot be deleted';
    END IF;
    IF NEW.run_id IS DISTINCT FROM OLD.run_id
       OR NEW.idempotency_key IS DISTINCT FROM OLD.idempotency_key
       OR NEW.command_hash IS DISTINCT FROM OLD.command_hash
       OR NEW.command_json IS DISTINCT FROM OLD.command_json
       OR NEW.trading_date IS DISTINCT FROM OLD.trading_date
       OR NEW.request_scope_hash IS DISTINCT FROM OLD.request_scope_hash
       OR NEW.policy_id IS DISTINCT FROM OLD.policy_id
       OR NEW.policy_hash IS DISTINCT FROM OLD.policy_hash
       OR NEW.provider_configuration_id IS DISTINCT FROM OLD.provider_configuration_id
       OR NEW.provider_configuration_hash IS DISTINCT FROM OLD.provider_configuration_hash
       OR NEW.research_configuration_id IS DISTINCT FROM OLD.research_configuration_id
       OR NEW.research_configuration_hash IS DISTINCT FROM OLD.research_configuration_hash
       OR NEW.created_at IS DISTINCT FROM OLD.created_at THEN
        RAISE EXCEPTION 'Continuous Research run identity is immutable';
    END IF;
    IF NEW.version != OLD.version + 1 THEN
        RAISE EXCEPTION 'Continuous Research run version must advance by one';
    END IF;
    IF OLD.status = 'ARCHIVED' AND NEW IS DISTINCT FROM OLD THEN
        RAISE EXCEPTION 'Archived Continuous Research run is immutable';
    END IF;
    RETURN NEW;
END;
$$;

CREATE TRIGGER continuous_research_run_no_delete
BEFORE DELETE ON continuous_research_run
FOR EACH ROW EXECUTE FUNCTION guard_continuous_research_run_mutation();
CREATE TRIGGER continuous_research_run_identity_immutable
BEFORE UPDATE ON continuous_research_run
FOR EACH ROW EXECUTE FUNCTION guard_continuous_research_run_mutation();

CREATE FUNCTION guard_continuous_runtime_tick_mutation()
RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    IF TG_OP = 'DELETE' THEN
        RAISE EXCEPTION 'Continuous Runtime ticks cannot be deleted';
    END IF;
    IF NEW.run_id IS DISTINCT FROM OLD.run_id
       OR NEW.tick_id IS DISTINCT FROM OLD.tick_id
       OR NEW.idempotency_key IS DISTINCT FROM OLD.idempotency_key
       OR NEW.tick_hash IS DISTINCT FROM OLD.tick_hash
       OR NEW.tick_json IS DISTINCT FROM OLD.tick_json
       OR NEW.tick_sequence IS DISTINCT FROM OLD.tick_sequence
       OR NEW.observed_at IS DISTINCT FROM OLD.observed_at
       OR NEW.session_phase IS DISTINCT FROM OLD.session_phase
       OR NEW.created_at IS DISTINCT FROM OLD.created_at THEN
        RAISE EXCEPTION 'Continuous Runtime tick identity is immutable';
    END IF;
    IF NEW.version != OLD.version + 1 THEN
        RAISE EXCEPTION 'Continuous Runtime tick version must advance by one';
    END IF;
    IF OLD.status IN ('COMPLETED', 'FAILED', 'DATA_BLOCKED')
       AND NEW IS DISTINCT FROM OLD THEN
        RAISE EXCEPTION 'Terminal Continuous Runtime tick is immutable';
    END IF;
    IF OLD.status = 'IN_PROGRESS' AND NEW.status = 'IN_PROGRESS' AND (
        NEW.claim_id IS DISTINCT FROM OLD.claim_id
        OR NEW.fencing_token IS DISTINCT FROM OLD.fencing_token
    ) THEN
        RAISE EXCEPTION 'Active Continuous Runtime claim cannot be overwritten';
    END IF;
    RETURN NEW;
END;
$$;

CREATE TRIGGER continuous_runtime_tick_no_delete
BEFORE DELETE ON continuous_runtime_tick
FOR EACH ROW EXECUTE FUNCTION guard_continuous_runtime_tick_mutation();
CREATE TRIGGER continuous_runtime_tick_terminal_immutable
BEFORE UPDATE ON continuous_runtime_tick
FOR EACH ROW EXECUTE FUNCTION guard_continuous_runtime_tick_mutation();

