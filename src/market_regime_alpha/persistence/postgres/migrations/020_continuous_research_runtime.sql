CREATE FUNCTION guard_continuous_current_evidence_mutation()
RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    IF TG_OP = 'DELETE' THEN
        RAISE EXCEPTION 'Continuous current Evidence cannot be deleted';
    END IF;
    IF NEW.run_id IS DISTINCT FROM OLD.run_id
       OR NEW.evidence_scope IS DISTINCT FROM OLD.evidence_scope THEN
        RAISE EXCEPTION 'Continuous current Evidence scope is immutable';
    END IF;
    IF NEW.version != OLD.version + 1 THEN
        RAISE EXCEPTION 'Continuous current Evidence version must advance by one';
    END IF;
    IF NEW.last_accepted_fencing_token < OLD.last_accepted_fencing_token THEN
        RAISE EXCEPTION 'Continuous current Evidence fencing token cannot regress';
    END IF;
    IF NEW.evidence_commit_id = OLD.evidence_commit_id
       OR NEW.material_identity_hash = OLD.material_identity_hash THEN
        RAISE EXCEPTION 'Identical Evidence must not advance current Evidence';
    END IF;
    RETURN NEW;
END;
$$;

